//! Regenerates `src/assets/fof2_grid.tsv`, the bundled foF2 climatology table.
//!
//! The table is data, bundled and checked in, so nothing is computed or fetched
//! at runtime. This generator exists so that the data's provenance is a
//! checked-in program rather than a pasted blob: run it and the file is
//! reproduced exactly, and `fof2::tests::bundled_grid_matches_its_generator`
//! fails if the two ever drift apart.
//!
//! **The values are NOT CCIR, URSI or IRI coefficients.** See the provenance
//! section of `crate::fof2`'s module documentation before using the numbers for
//! anything.
//!
//! ```text
//! cargo run -p skipzone-app --bin gen_fof2_grid
//! ```

use std::fmt::Write as _;

use skipzone_app::fof2::{
    GRID_LAT_MIN_DEG, GRID_LAT_ROWS, GRID_LAT_STEP_DEG, GRID_LST_COLS, GRID_LST_STEP_H,
    GRID_SSN_LEVELS, climatology_fof2,
};
use skipzone_app::solar::Season;

fn main() -> std::io::Result<()> {
    let mut out = String::new();
    out.push_str(
        "# foF2 climatology grid, MHz.\n\
         #\n\
         # GENERATED by src/bin/gen_fof2_grid.rs from fof2::climatology_fof2. Do not edit by\n\
         # hand: the test fof2::tests::bundled_grid_matches_its_generator compares the two.\n\
         #\n\
         # THESE ARE NOT CCIR, URSI OR IRI COEFFICIENTS. The layout follows the operational\n\
         # maps (latitude x local solar time, per season, at two solar-activity levels\n\
         # interpolated in NmF2) so that real coefficient data drops in as a file\n\
         # replacement, but the values are an order-of-magnitude climatology calibrated only\n\
         # to fof2::fof2_from_ssn. See the provenance section of fof2's module docs.\n\
         #\n\
         # Columns: season, ssn, latitude_deg, then foF2 at local solar time\n\
         # 0, 1, ... 23 h. Season is the LOCAL season (already hemisphere-flipped by the\n\
         # caller), so a row's latitude sign carries no seasonal meaning.\n",
    );
    let _ = writeln!(
        out,
        "# Lattice: {GRID_LAT_ROWS} latitude rows from {GRID_LAT_MIN_DEG} deg at \
         {GRID_LAT_STEP_DEG} deg, {GRID_LST_COLS} local-time columns at {GRID_LST_STEP_H} h \
         (periodic)."
    );

    for (season, name) in [
        (Season::Winter, "winter"),
        (Season::Equinox, "equinox"),
        (Season::Summer, "summer"),
    ] {
        for level in GRID_SSN_LEVELS {
            for row in 0..GRID_LAT_ROWS {
                #[allow(clippy::cast_precision_loss)]
                let lat = GRID_LAT_MIN_DEG + row as f64 * GRID_LAT_STEP_DEG;
                let _ = write!(out, "{name}\t{level:.0}\t{lat:.0}");
                for col in 0..GRID_LST_COLS {
                    #[allow(clippy::cast_precision_loss)]
                    let lst = col as f64 * GRID_LST_STEP_H;
                    let _ = write!(out, "\t{:.4}", climatology_fof2(lat, lst, season, level));
                }
                out.push('\n');
            }
        }
    }

    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/src/assets/fof2_grid.tsv");
    std::fs::write(path, &out)?;
    println!("wrote {path} ({} bytes)", out.len());
    Ok(())
}
